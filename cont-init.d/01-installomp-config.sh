#!/bin/sh
# /etc/cont-init.d/01-installomp-config.sh — headless omp config
#
# Generates the agent-side omp configuration at every boot (idempotent):
#   ~/.omp/agent/models.yml  — custom provider `cig` → the loopback
#                              cig-adapter (api: openai-completions), with
#                              the CIG roster models (D1).
#   ~/.omp/agent/config.yml  — modelRoles per the D1 map (approved
#                              2026-11-04): default/task/plan → main roster
#                              model; slow → strongest; smol/tiny/commit →
#                              cheapest. advisor/vision intentionally UNSET
#                              (token-budget guard — open item: verify
#                              unset-role semantics against omp docs; if
#                              unset falls back to default rather than
#                              disabling, pin them to the cheapest model).
#   $OMP_WORKSPACE/AGENTS.md — the agent persona + name (AGENT_NAME env).
#
# MUST SUCCEED (bootstrap contract — a failure aborts the container).
set -eu

AGENT_UID="${AGENT_UID:-10000}"
STATE_HOME="${OMP_STATE_HOME:-/home/agent}"
CFG_DIR="$STATE_HOME/.omp/agent"
WORKSPACE="${OMP_WORKSPACE:-$STATE_HOME/workspace}"
ADAPTER_PORT="${CIG_ADAPTER_PORT:-18900}"

ADAPTER_KEY="${CIG_ADAPTER_KEY:-}"
if [ -z "$ADAPTER_KEY" ]; then
  echo "[installomp-config] FATAL: CIG_ADAPTER_KEY is not set — the cig provider cannot authenticate" >&2
  exit 111
fi

DEFAULT_MODEL="${OMP_MODEL_DEFAULT:-glm-5.2}"
SLOW_MODEL="${OMP_MODEL_SLOW:-deepseek-v4-pro}"
SMOL_MODEL="${OMP_MODEL_SMOL:-deepseek-v4-flash-0731}"

mkdir -p "$CFG_DIR" "$WORKSPACE"

# --- models.yml: the cig provider + roster (dedup, order-stable) ---
ROSTER="$(printf '%s\n' "$DEFAULT_MODEL" "$SLOW_MODEL" "$SMOL_MODEL" $OMP_MODELS_EXTRA | awk 'NF && !seen[$0]++')"

{
  echo "# Generated by installomp cont-init — regenerated at every boot. Do not edit."
  echo "# Custom OpenAI-compatible provider: the loopback CIG adapter."
  echo "providers:"
  echo "  cig:"
  echo "    baseUrl: http://127.0.0.1:${ADAPTER_PORT}/v1"
  echo "    api: openai-completions"
  echo "    apiKey: ${ADAPTER_KEY}"
  echo "    models:"
  echo "$ROSTER" | while IFS= read -r m; do
    [ -n "$m" ] || continue
    printf '      - id: %s\n' "$m"
    printf '        name: %s\n' "$m"
    printf '        contextWindow: 131072\n'
    printf '        maxTokens: 32768\n'
  done
} > "$CFG_DIR/models.yml"

# --- config.yml: the D1 role map ---
cat > "$CFG_DIR/config.yml" <<EOF
# Generated by installomp cont-init — regenerated at every boot. Do not edit.
# D1 (approved 2026-11-04): default/task/plan -> main; slow -> strongest;
# smol/tiny/commit -> cheapest. advisor/vision deliberately unset.
modelRoles:
  default: cig/${DEFAULT_MODEL}
  task: cig/${DEFAULT_MODEL}
  plan: cig/${DEFAULT_MODEL}
  slow: cig/${SLOW_MODEL}
  smol: cig/${SMOL_MODEL}
  tiny: cig/${SMOL_MODEL}
  commit: cig/${SMOL_MODEL}
EOF

# --- workspace AGENTS.md: persona + name (AGENT_NAME env; BACK-IOC-014
#     convention: the user names their agent at claim time) ---
AGENT_NAME="${AGENT_NAME:-OMP Agent}"
cat > "$WORKSPACE/AGENTS.md" <<EOF
# ${AGENT_NAME}

You are ${AGENT_NAME} — a hosted OMP coding agent.

- You run on the user's own hosted instance. Inference is sovereign and metered.
- Work in this workspace (\$PWD). Keep changes scoped to it.
- Be direct and concise. Ship working code. Explain after.
- This file is the user's to edit — it is their agent, their rules.
EOF

# --- ownership ---
chown -R "${AGENT_UID}:${AGENT_UID}" "$STATE_HOME/.omp" "$WORKSPACE" 2>/dev/null || {
  # Fred degraded-root backends EPERM chown (hermes v9 lesson) — tolerate:
  # config is still functional as root-owned when services run as root.
  echo "[installomp-config] NOTE: chown to agent uid failed — degraded-root backend (config remains functional)"
}

echo "[installomp-config] wrote $CFG_DIR/models.yml ($(echo "$ROSTER" | grep -c .) models) + $CFG_DIR/config.yml + $WORKSPACE/AGENTS.md"
